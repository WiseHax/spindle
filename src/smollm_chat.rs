    /// Takes the average cluster timing breakdown (worker_ms, local_ms) for the completed turn.
    pub fn take_cluster_timing(&mut self) -> Option<(f64, f64)> {
        if self.timing.steps == 0 {
            return None;
        }
        let w_avg_ms = (self.timing.worker_us as f64 / self.timing.steps as f64) / 1000.0;
        let l_avg_ms = (self.timing.local_us as f64 / self.timing.steps as f64) / 1000.0;
        self.timing = StepTiming::default();
        Some((w_avg_ms, l_avg_ms))
    }

    /// Locks up to `budget` bytes of weights into RAM and returns how many were locked.
    ///
    /// Why: every token reads the layers in the same order, 0..n, then starts over. The
    /// working set behaves roughly like an LRU cache, and LRU on a cyclic scan bigger than the
    /// cache evicts exactly the page that is needed next, so nearly every access misses.
    /// Pinning a fixed part of the model turns that part into guaranteed hits and leaves only
    /// the rest cycling. Every pinned byte saves one page-in per token, so which bytes are
    /// pinned matters less than how many; dense weights that every token reads come first,
    /// MoE experts (each used by only some tokens) are never pinned.
    pub fn pin_hot_weights(&self, budget: usize) -> usize {
        self.pin_weights(budget, 0, &mut |_, _| {}).total()
    }

    /// `pin_hot_weights`, then the most-used MoE experts (by the counts of earlier sessions)
    /// while they fit, leaving `expert_headroom` bytes of the budget unpinned so rare experts
    /// still have room to page in. `progress(done, total)` reports locked bytes.
    pub fn pin_weights(&self, budget: usize, expert_headroom: usize, progress: &mut dyn FnMut(u64, u64)) -> PinPlan {
        let c = self.cfg;
        let mut spans = vec![span(&self.lm_head), (self.output_norm, c.dim * 4)];
        for ly in &self.layers {
            spans.extend([(ly.attn_norm, c.dim * 4), (ly.ffn_norm, c.dim * 4)]);
            spans.extend([span(&ly.wq), span(&ly.wk), span(&ly.wv), span(&ly.wo)]);
            match &ly.ffn {
                FfnKind::Dense(f) => spans.extend(f.spans()),
                FfnKind::Moe(m) => {
                    spans.push(span(&m.router));
                    if let Some(sh) = &m.shared {
                        spans.extend(sh.spans());
                    }
                }
            }
        }
        let mut chosen = Vec::new();
        let mut total = 0;
        for s in spans {
            if chosen.iter().any(|&(off, _)| off == s.0) {
                continue; // tied embedding / LM head
            }
            if total + s.1 > budget {
                continue; // too big for what's left; smaller tensors later may still fit
            }
            total += s.1;
            chosen.push(s);
        }
        let dense = total;
        // Experts, most picked first. Only experts that were actually picked before count.
        let mut plan = PinPlan::default();
        let expert_budget = budget.saturating_sub(expert_headroom);
        let total_prior: u64 = self.prior_picks.iter().map(|&c| c as u64).sum();
        let mut covered = 0u64;
        for (layer, e, count) in self.hot_experts() {
            let FfnKind::Moe(m) = &self.layers[layer - self.layer_range.start].ffn else { continue };
            let spans = m.experts.expert(e).spans();
            let bytes: usize = spans.iter().map(|s| s.1).sum();
            if total + bytes > expert_budget {
                break;
            }
            total += bytes;
            chosen.extend(spans);
            plan.experts += 1;
            plan.pinned.push((layer, e));
            covered += count as u64;
        }
        if total == 0 || !crate::memory_guard::allow_locking((total + 64 * 1024 * 1024) as u64) {
            return plan;
        }
        // Lock in pieces so the startup display can show progress.
        let mut locked = 0usize;
        for piece in chosen.chunks(48) {
            locked += self.raw_bytes.lock_ranges(piece);
            progress(locked as u64, total as u64);
        }
        plan.dense_bytes = locked.min(dense);
        plan.expert_bytes = locked.saturating_sub(dense);
        plan.coverage = (total_prior > 0).then(|| covered as f64 / total_prior as f64);
        plan.has_stats = total_prior > 0;
        plan
    }

    /// Records which experts `pin_weights` locked, for resident-only routing.
    pub fn set_resident_experts(&mut self, experts: &[(usize, usize)]) {
        self.resident_experts = experts.to_vec();
        if self.resident_only {
            self.apply_resident_masks();
        }
    }

    /// Resident-only routing: each MoE layer picks only among the experts locked in RAM, so
    /// nothing is read from disk while generating. It changes the output (like `moe_prune`),
    /// so it is off by default. It has no effect when nothing was pinned (the whole share fits
    /// in RAM, or there is no usage history yet). On a cluster the worker applies it to its
    /// own layers with its own pinned set. Returns whether routing is restricted here.
    pub fn set_resident_only(&mut self, on: bool) -> bool {
        self.resident_only = on;
        if let Some(c) = self.cluster_client.as_mut() {
            let _ = c.set_resident_only(on);
        }
        self.apply_resident_masks()
    }

    fn apply_resident_masks(&mut self) -> bool {
        let start = self.layer_range.start;
        let on = self.resident_only && !self.resident_experts.is_empty();
        let mut any = false;
        for (i, ly) in self.layers.iter_mut().enumerate() {
            if let FfnKind::Moe(m) = &mut ly.ffn {
                m.resident = None;
                if on && m.n_expert <= 256 {
                    let mut mask = [0u64; 4];
                    for &(l, e) in &self.resident_experts {
                        if l == start + i {
                            mask[e / 64] |= 1 << (e % 64);
                        }
                    }
                    m.resident = Some(mask);
                    any = true;
                }
            }
        }
        any
    }

    /// Identifies the resident set when resident-only routing is on (0 when it is off), so
    /// prompt caches saved under one routing are never loaded under another.
    pub fn resident_hash(&self) -> u64 {
        if !self.resident_only || self.resident_experts.is_empty() {
            return 0;
        }
        let mut v = self.resident_experts.clone();
        v.sort_unstable();
        let mut h = Fnv64::new();
        h.bytes(b"resident");
        for (l, e) in v {
            h.u64((l as u64) << 32 | e as u64);
        }
        h.finish()
    }

    /// Perplexity of the model on `text` (no chat framing), over at most `max_tokens`
    /// tokens: exp of the mean negative log-likelihood of each next token. Lower is better.
    /// Used to measure what settings that change the output (MoE pruning, resident-only
    /// routing, wire format) cost in quality. Clears the conversation. Returns
    /// `(perplexity, tokens scored)`.
    pub unsafe fn perplexity(&mut self, text: &str, max_tokens: usize, progress: &mut dyn FnMut(usize, usize)) -> (f64, usize) {
        self.reset_kv();
        let mut ids: Vec<usize> = self.bos.into_iter().collect();
        ids.extend(self.encode_bpe_segment(text));
        ids.truncate(max_tokens.min(self.max_seq));
        let n = ids.len();
        if n < 2 {
            return (f64::NAN, 0);
        }
        let vocab = self.cfg.vocab;
        let scale = self.cfg.logit_scale;
        let (mut nll, mut scored) = (0.0f64, 0usize);
        let mut pos = 0;
        for chunk in ids.chunks(32) {
            let hs = self.verify_forward(chunk, pos);
            self.compute_logits_batch(&hs);
            for i in 0..chunk.len() {
                let next = pos + i + 1;
                if next >= n {
                    break;
                }
                let row = &self.batch_logits[i * vocab..(i + 1) * vocab];
                let max = row.iter().fold(f32::NEG_INFINITY, |a, &b| a.max(b / scale)) as f64;
                let lse = max + row.iter().map(|&x| ((x / scale) as f64 - max).exp()).sum::<f64>().ln();
                nll += lse - (row[ids[next]] / scale) as f64;
                scored += 1;
            }
            pos += chunk.len();
            self.cur_pos = pos;
            progress(pos, n);
        }
        self.reset_kv();
        ((nll / scored.max(1) as f64).exp(), scored)
    }

    /// This node's experts that earlier sessions picked, most picked first:
    /// `(global layer, expert, picks)`.
    fn hot_experts(&self) -> Vec<(usize, usize, u32)> {
        let n_expert = self.cfg.n_expert.max(1);
        let mut v: Vec<(usize, usize, u32)> = self
            .prior_picks
            .iter()
            .enumerate()
            .filter(|&(_, &c)| c > 0)
            .map(|(i, &c)| (i / n_expert, i % n_expert, c))
            .filter(|&(l, _, _)| self.layer_range.contains(&l) && matches!(self.layers[l - self.layer_range.start].ffn, FfnKind::Moe(_)))
            .collect();
        v.sort_unstable_by(|a, b| b.2.cmp(&a.2));
        v
    }

    /// `<model>.experts-<layers>.bin`: expert pick counts kept across sessions.
    fn expert_stats_path(&self) -> std::path::PathBuf {
        std::path::PathBuf::from(format!("{}.experts-{}-{}.bin", self.path, self.layer_range.start, self.layer_range.end))
    }

    /// Reads the counts saved by earlier sessions into `prior_picks` and the live counters.
    /// A missing or mismatched file just means no history.
    fn load_expert_stats(&mut self) {
        let Ok(b) = std::fs::read(self.expert_stats_path()) else { return };
        let total = self.cfg.n_layers * self.cfg.n_expert;
        if b.len() != 12 + total * 4 || &b[0..4] != EXPERT_STATS_MAGIC {
            return;
        }
        let rd = |i: usize| u32::from_le_bytes(b[i..i + 4].try_into().unwrap());
        if rd(4) as usize != self.cfg.n_layers || rd(8) as usize != self.cfg.n_expert {
            return;
        }
        let counts: Vec<u32> = (0..total).map(|i| rd(12 + i * 4)).collect();
        for (dst, &c) in self.moe_stats.picks.iter_mut().zip(&counts) {
            *dst = dst.saturating_add(c);
        }
        self.prior_picks = counts;
    }

    /// Writes the pick counts (earlier sessions plus this one). Atomic: temp file + rename.
    pub fn save_expert_stats(&mut self) -> std::io::Result<()> {
        if !self.is_moe() {
            return Ok(());
        }
        let mut b = Vec::with_capacity(12 + self.moe_stats.picks.len() * 4);
        b.extend_from_slice(EXPERT_STATS_MAGIC);
        b.extend_from_slice(&(self.cfg.n_layers as u32).to_le_bytes());
        b.extend_from_slice(&(self.cfg.n_expert as u32).to_le_bytes());
        for &c in &self.moe_stats.picks {
            b.extend_from_slice(&c.to_le_bytes());
        }
        let path = self.expert_stats_path();
        let tmp = path.with_extension("bin.tmp");
        std::fs::write(&tmp, &b)?;
        std::fs::rename(&tmp, &path)?;
        self.stats_saved_at = Some(std::time::Instant::now());
        Ok(())
    }

    /// Saves the pick counts at most once a minute (a 24 KB write for Qwen3-30B-A3B).
    pub fn maybe_save_expert_stats(&mut self) {
        if self.stats_saved_at.map_or(true, |t| t.elapsed() >= std::time::Duration::from_secs(60)) {
            let _ = self.save_expert_stats();
        }
    }

    /// Decides what lives in RAM for a model that doesn't fit, given `budget` bytes for
    /// weights. The LM head (read in full every token) is pinned first, then whole layers
    /// from layer 0 while they fit. The remaining layers are streamed with one read each
    /// through two buffers (which come out of the budget). Models whose layers aren't
    /// contiguous (MoE) fall back to `pin_hot_weights`. Returns `(pinned bytes, first
    /// streamed layer)`.
    ///
    /// Streaming is opt-in (`stream_layers`): measured on Qwen3-0.6B it matched mmap paging
    /// under a tight cap (both ~7-8 tok/s, both drive-limited) while cutting page faults
    /// ~100x, but it is planned once at startup and can't grow into RAM that frees up later,
    /// so by default (pin + mmap) wins whenever memory loosens.
    pub fn plan_residency(&mut self, budget: usize, stream_layers: bool) -> (usize, Option<usize>) {
        let spans = match (&self.layer_spans, stream_layers) {
            (Some(s), true) => s.clone(),
            _ => return (self.pin_hot_weights(budget), None),
        };
        self.plan_layer_stream(budget, spans)
    }

    fn plan_layer_stream(&mut self, budget: usize, spans: Vec<(usize, usize)>) -> (usize, Option<usize>) {
        let n = spans.len();
        let max_span = spans.iter().map(|s| s.1).max().unwrap_or(0);
        // Two stream buffers, unless everything ends up pinned anyway.
        let mut left = budget.saturating_sub(2 * max_span);
        let mut chosen = Vec::new();
        let head = (span(&self.lm_head), (self.output_norm, self.cfg.dim * 4));
        if head.0 .1 + head.1 .1 <= left {
            left -= head.0 .1 + head.1 .1;
            chosen.extend([head.0, head.1]);
        }
        let mut first = 0;
        while first < n && spans[first].1 <= left {
            left -= spans[first].1;
            chosen.push(spans[first]);
            first += 1;
        }
        let want = chosen.iter().map(|s| s.1).sum::<usize>();
        let pinned = if want > 0 && crate::memory_guard::allow_locking((want + 64 * 1024 * 1024) as u64) {
            self.raw_bytes.lock_ranges(&chosen)
        } else {
            0
        };
        if first == n {
            return (pinned, None);
        }
        match crate::layer_stream::LayerStreamer::new(&self.path, spans, first) {
            Ok(s) => {
                self.streamer = Some(s);
                (pinned, Some(first))
            }
            Err(e) => {
                crate::ui::note(&format!("layer streaming unavailable ({e}), paging layers instead"));
                (pinned, None)
            }
        }
    }

    /// Bytes of model weights read from the file by the layer streamer so far.
    pub fn streamed_bytes(&self) -> u64 {
        self.streamer.as_ref().map_or(0, |s| s.bytes_read)
    }

    /// True when the model was too big to prefetch, so weights page in as they're used.
    pub fn is_streaming(&self) -> bool {
        self.prefetcher.is_some()
    }

    /// Private memory this engine keeps resident: KV-cache plus per-token scratch.
    pub fn private_bytes_estimate(&self) -> u64 {
        let buffers = self.streamer.as_ref().map_or(0, |s| 2 * s.max_buffer())
            + self.expert_cache.as_ref().map_or(0, |c| c.bytes());
        ((self.k_cache.len() + self.v_cache.len()) * 2 + self.cfg.vocab * 8 + 64 * 1024 * 1024 + buffers) as u64
    }

    pub fn is_moe(&self) -> bool {
        self.cfg.n_expert > 0
    }

    /// Expert pick counts for this node's MoE layers since load: `(global layer, picks per
    /// expert, bytes of one expert)`.
    pub fn expert_picks(&self) -> Vec<ExpertPicks> {
        let mut out = Vec::new();
        for (i, ly) in self.layers.iter().enumerate() {
            if let FfnKind::Moe(m) = &ly.ffn {
                let layer = self.layer_range.start + i;
                let row = &self.moe_stats.picks[layer * m.n_expert..(layer + 1) * m.n_expert];
                out.push(ExpertPicks { layer, picks: row.to_vec(), expert_bytes: m.experts.expert(0).bytes() as u64 });
            }
        }
        out
    }

    /// `(MiB of expert weights read per token, experts touched, total experts, timing)` for the
    /// turn so far, then resets the counters.
    pub fn take_moe_stats(&mut self) -> Option<(f64, usize, usize, MoeTiming)> {
        if !self.is_moe() {
            return None;
        }
        let s = &mut self.moe_stats;
        let per_tok = s.expert_bytes as f64 / s.tokens.max(1) as f64 / (1024.0 * 1024.0);
        let touched = s.touched.iter().filter(|&&t| t).count();
        let total = s.touched.len();
        let timing = s.timing;
        s.tokens = 0;
        s.expert_bytes = 0;
        s.touched.fill(false);
        s.timing = MoeTiming::default();
        Some((per_tok, touched, total, timing))
    }

    /// Repacks all MoE expert weights into a single contiguous 4096-aligned sidecar file
    /// `<model>.spindle.pack`. Returns the written `PackIndex`.
    pub fn repack_moe_experts<P: FnMut(usize, usize, u64, u64)>(&self, progress: P) -> std::io::Result<crate::expert_pack::PackIndex> {
        if !self.is_moe() {
            return Err(std::io::Error::new(std::io::ErrorKind::InvalidInput, "model has no MoE layers"));
        }
        let pack_path = crate::expert_pack::pack_path_for_model(&self.path);
        let expert_spans = |l: usize, e: usize| -> [(usize, usize); 3] {
            match &self.layers[l].ffn {
                FfnKind::Moe(m) => m.experts.expert(e).spans(),
                _ => panic!("layer {l} is not an MoE layer"),
            }
        };
        crate::expert_pack::repack_experts(
            &self.raw_bytes,
            self.raw_bytes.len() as u64,
            &pack_path,
            self.cfg.n_layers,
            self.cfg.n_expert,
            &expert_spans,
            progress,
        )
    }

    /// Opens an in-RAM expert cache with the specified budget. Uses `<model>.spindle.pack`
    /// when a valid one exists, otherwise reads experts straight from the GGUF, which needs
    /// no extra disk space (a pack duplicates every expert).
    pub fn enable_expert_cache(&mut self, budget_bytes: usize) -> std::io::Result<()> {
        if !self.is_moe() {
            return Ok(());
        }
        let n_expert = self.cfg.n_expert;
        // Expert sizes can differ per layer (mixed quants such as Q4_K_M), so each expert
        // carries its own spans. Non-MoE layers get empty entries and are never requested.
        let segments: Vec<crate::expert_cache::ExpertSegments> = self
            .layers
            .iter()
            .flat_map(|l| {
                (0..n_expert).map(move |e| match &l.ffn {
                    FfnKind::Moe(m) => m.experts.expert(e).spans().map(|(off, len)| (off as u64, len)),
                    _ => [(0, 0); 3],
                })
            })
            .collect();
        let max_payload = segments.iter().map(|s| s.iter().map(|x| x.1).sum::<usize>()).max().unwrap_or(0) as u64;

        let pack_path = crate::expert_pack::pack_path_for_model(&self.path);
        let (cache, source) = if crate::expert_pack::is_pack_valid(&self.path, &pack_path) {
            let h = std::fs::File::open(&pack_path)
                .and_then(|mut f| crate::expert_pack::PackIndex::read_from_file(&mut f))?
                .hdr;
            let first = segments.iter().find(|s| s[0].1 > 0);
            let shape_ok = h.n_layers as usize == self.cfg.n_layers
                && h.n_expert as usize == n_expert
                && max_payload <= h.expert_slot_bytes
                && first.is_some_and(|s| (s[0].1 as u64, s[1].1 as u64, s[2].1 as u64) == (h.gate_bytes, h.up_bytes, h.down_bytes));
            if !shape_ok {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::InvalidData,
                    format!("{pack_path} doesn't match this model's experts; delete it and run --pack-experts again"),
                ));
            }
            (crate::expert_cache::ExpertCache::open(&pack_path, budget_bytes)?, "pack")
        } else {
            let c = crate::expert_cache::ExpertCache::open_gguf(&self.path, segments, self.cfg.n_layers, n_expert, budget_bytes)?;
            (c, "gguf")
        };
        crate::vlog!(
            "[expert:cache] enabled in-RAM cache from {source}: {} expert slots ({:.1} MiB budget), slot size {:.2} MiB",
            cache.capacity(),
            (cache.capacity() * cache.slot_bytes) as f64 / (1024.0 * 1024.0),
            cache.slot_bytes as f64 / (1024.0 * 1024.0)
        );
        self.expert_cache = Some(cache);
        Ok(())
    }

    /// Makes room for `needed` more positions by evicting the oldest non-system tokens.
    /// Kept tokens slide down by `n_discard` positions; since K was cached *after* RoPE,
    /// each kept K vector is re-rotated by `-n_discard` so its position encoding stays
    /// consistent.
    pub fn ensure_kv_room(&mut self, needed: usize) {
        if self.cur_pos + needed <= self.max_seq {
            return;
        }
        let n_ctx = self.cur_pos - self.n_keep;
        // Evict at least what we need, rounded up to half the window to amortize the shift.
        let want = (self.cur_pos + needed - self.max_seq).max(n_ctx / 2);
        let n_discard = want.min(n_ctx);
        // The cluster worker holds the other layers' KV for the same positions: it must
        // drop exactly the same tokens, or every later position desyncs.
        if let Some(client) = self.cluster_client.as_mut() {
            client
                .kv_shift(self.n_keep, n_discard, self.cur_pos)
                .expect("cluster worker KV shift failed");
        }
        self.shift_kv(n_discard);
    }

    /// Drops `n_discard` tokens right after the `n_keep` pinned (system) positions, moving the
    /// rest down and re-rotating their keys so RoPE positions stay consistent.
    pub fn shift_kv(&mut self, n_discard: usize) {
        let c = self.cfg;
        let n_ctx = self.cur_pos.saturating_sub(self.n_keep);
        let n_discard = n_discard.min(n_ctx);
        if n_discard == 0 {
            return;
        }
        let n_move = n_ctx - n_discard;

        let mut k_tmp = vec![0.0f32; c.kv_dim];
        for l in 0..self.layers.len() {
            let layer = l * self.max_seq;
            for i in 0..n_move {
                let src = (layer + self.n_keep + n_discard + i) * c.kv_dim;
                let dst = (layer + self.n_keep + i) * c.kv_dim;
                // SAFETY: main checks for AVX2/F16C at startup; kv_dim is a multiple of 8.
                unsafe {
                    f16_to_f32_slice(&self.k_cache[src..src + c.kv_dim], &mut k_tmp);
                    self.rope.rotate(&mut k_tmp, c.head_dim, -(n_discard as f32));
                    f32_to_f16_slice(&k_tmp, &mut self.k_cache[dst..dst + c.kv_dim]);
                }
                self.v_cache.copy_within(src..src + c.kv_dim, dst);
            }
        }
        self.cur_pos -= n_discard;
        self.kv_shifts += 1;
        crate::vlog!("[kv:shift] evicted {n_discard} old tokens (kept {} system + {n_move} recent)", self.n_keep);
    }

    /// Appends tokens to the prompt-lookup corpus, dropping the oldest half when full.
    fn remember_tokens(&mut self, ids: &[usize]) {
        self.lookup_corpus.extend_from_slice(ids);
        if self.lookup_corpus.len() > LOOKUP_CORPUS_MAX {
            let drop = self.lookup_corpus.len() - LOOKUP_CORPUS_MAX / 2;
            self.lookup_corpus.drain(..drop);
        }
    }

    /// Prompt-lookup drafting: finds the most recent earlier occurrence of the corpus's last
    /// `n` tokens (longest `n` first) and proposes the up-to-`k` tokens that followed it.
    /// Code edits, quoted files and tool output repeat a lot, so these drafts are often right;
    /// when they're wrong, verification simply rejects them (the output never changes).
    /// Returns the draft and the n-gram length that matched (0 = no draft).
    pub fn lookup_draft(&self, k: usize) -> (Vec<usize>, usize) {
        let c = &self.lookup_corpus;
        let n = c.len();
        if k == 0 {
            return (Vec::new(), 0);
        }
        for ng in (LOOKUP_MIN_NGRAM..=LOOKUP_MAX_NGRAM).rev() {
            if n <= ng {
                continue;
            }
            let pat = &c[n - ng..];
            // Candidate starts must end before the suffix itself.
            let mut i = n - ng;
            while i > 0 {
                i -= 1;
                if c[i + ng - 1] == pat[ng - 1] && c[i..i + ng] == *pat {
                    let s = i + ng;
                    // A 2-token match is weak evidence: propose less.
                    let kk = if ng == LOOKUP_MIN_NGRAM { k.min(2) } else { k };
                    let e = (s + kk).min(n);
                    let draft: Vec<usize> = c[s..e].iter().copied().take_while(|t| !self.stop_ids.contains(t)).collect();
                    if !draft.is_empty() {
                        return (draft, ng);
                    }
                }
            }
        }
        (Vec::new(), 0)
    }

    /// Runs `batch` (the pending token + drafts) at `start_pos` through the whole model in one
    /// layer-synchronous pass (one cluster round trip) and returns every final hidden state.
    unsafe fn verify_forward(&mut self, batch: &[usize], start_pos: usize) -> Vec<Vec<f32>> {
        if let Some(mut client) = self.cluster_client.take() {
            let t_w = std::time::Instant::now();
            let w = client.prefill(batch, start_pos).expect("cluster verify (prefill) failed");
            let w_us = t_w.elapsed().as_micros() as u64;
            self.cluster_client = Some(client);
            let t_l = std::time::Instant::now();
            let h = self.forward_batch_slice(None, Some(&w), start_pos);
            self.timing.worker_us += w_us;
            self.timing.local_us += t_l.elapsed().as_micros() as u64;
            self.timing.steps += 1;
            self.timing.passes += 1;
            h
        } else {
            let t_l = std::time::Instant::now();
            let h = self.forward_batch(batch, start_pos);
            self.timing.local_us += us_since(t_l);
            self.timing.passes += 1;
            h
        }
    }

    /// Feeds `ids` into the KV-cache starting at `cur_pos` and returns the last hidden state.
    /// Processes up to 32 tokens per layer-synchronous batch so a multi-token prompt scans
    /// the model's layers once per chunk instead of once per token.
    unsafe fn feed(&mut self, ids: &[usize]) -> Vec<f32> {
        self.remember_tokens(ids);
        let mut last_hidden = vec![0.0f32; self.cfg.dim];
        if self.cluster_client.is_some() {
            for chunk in ids.chunks(128) {
                // With the client attached, so a shift is mirrored to the worker.
                self.ensure_kv_room(chunk.len());
                let c = self.cluster_client.as_mut().unwrap();
                let worker_hiddens = c
                    .prefill(chunk, self.cur_pos)
                    .expect("cluster prefill failed");
                let mut hiddens =
                    self.forward_batch_slice(None, Some(&worker_hiddens), self.cur_pos);
                self.cur_pos += chunk.len();
                if let Some(h) = hiddens.pop() {
                    last_hidden = h;
                }
            }
            return last_hidden;
        }
        for chunk in ids.chunks(128) {
            self.ensure_kv_room(chunk.len());
            if chunk.len() == 1 {
                last_hidden = self.forward_hidden(chunk[0], self.cur_pos);
                self.cur_pos += 1;
            } else {
                let mut hiddens = self.forward_batch(chunk, self.cur_pos);
                self.cur_pos += chunk.len();
                if let Some(h) = hiddens.pop() {
                    last_hidden = h;
                }
            }
        }
        last_hidden
    }

    /// Evaluates one token at `pos`, coordinating with the cluster worker if connected.
    #[inline]
    pub unsafe fn step_token(&mut self, token_id: usize, pos: usize) -> Vec<f32> {
        if self.cluster_client.is_some() {
            let mut client = self.cluster_client.take().unwrap();
            let t_w = std::time::Instant::now();
            let worker_act = client.step(token_id, pos).expect("cluster worker step failed");
            let w_us = t_w.elapsed().as_micros() as u64;
            self.cluster_client = Some(client);

            let t_l = std::time::Instant::now();
            let act = self.forward_slice(None, Some(&worker_act), pos);
            let l_us = t_l.elapsed().as_micros() as u64;

            self.timing.worker_us += w_us;
            self.timing.local_us += l_us;
            self.timing.steps += 1;
            self.timing.passes += 1;
            act
        } else {
            let t_l = std::time::Instant::now();
            let h = self.forward_hidden(token_id, pos);
            self.timing.local_us += us_since(t_l);
            self.timing.passes += 1;
            h
        }
    }

    /// Runs a batch of tokens `token_ids` starting at `start_pos` synchronously layer-by-layer
    /// (`l in 0..n_layers` on the outer loop, `b in 0..token_ids.len()` on the inner loop) and
    /// returns the hidden state for each token in `token_ids`.
    #[inline]
    pub unsafe fn forward_batch(&mut self, token_ids: &[usize], start_pos: usize) -> Vec<Vec<f32>> {
        self.forward_batch_slice(Some(token_ids), None, start_pos)
    }

    /// Evaluates this engine's assigned layer partition (`self.layer_range`) for a batch of inputs.
    /// - If `token_ids` is Some, loads initial embeddings (Stage 0).
    /// - If `in_hiddens` is Some, uses the provided activation vectors from the upstream stage (Stage 1).
    #[target_feature(enable = "avx2,fma,f16c")]
    pub unsafe fn forward_batch_slice(
        &mut self,
        token_ids: Option<&[usize]>,
        in_hiddens: Option<&[Vec<f32>]>,
        start_pos: usize,
    ) -> Vec<Vec<f32>> {
        let bsz = token_ids.map_or_else(|| in_hiddens.map_or(0, |h| h.len()), |t| t.len());
        if bsz == 0 {
            return Vec::new();
        }
        if bsz == 1 {
            let tid = token_ids.map(|t| t[0]);
            let in_h = in_hiddens.map(|h| h[0].as_slice());
            return vec![self.forward_slice(tid, in_h, start_pos)];
        }
        let c = self.cfg;
        let base = self.raw_bytes.as_ptr();
        let pool = self.pool.as_ref();

        let mut xs: Vec<Vec<f32>> = match (token_ids, in_hiddens) {
            (Some(ids), _) => {
                let rb = row_bytes(self.embed.dtype, c.dim).expect("unsupported embedding type");
                ids.iter()
                    .map(|&tid| {
                        let row = std::slice::from_raw_parts(base.add(self.embed.offset + tid * rb), rb);
                        let mut x = dequant_row(self.embed.dtype, row, c.dim);
                        if c.embedding_scale != 1.0 {
                            x.iter_mut().for_each(|v| *v *= c.embedding_scale);
                        }
                        x
                    })
                    .collect()
            }
            (None, Some(hiddens)) => hiddens.to_vec(),
            (None, None) => return Vec::new(),
        };

        let mut x_norms = vec![vec![0.0f32; c.dim]; bsz];
        let mut proj_outs = vec![vec![0.0f32; c.dim]; bsz];
        let mut qs = vec![vec![0.0f32; c.q_dim]; bsz];
        let mut ks = vec![vec![0.0f32; c.kv_dim]; bsz];
        let mut vs = vec![vec![0.0f32; c.kv_dim]; bsz];
        let mut attn_outs = vec![vec![0.0f32; c.q_dim]; bsz];
        let mut ffn_scratch: Vec<f32> = Vec::new();
        if self.is_moe() {
            self.moe_stats.tokens += bsz;
        }

        let hint = self.prefetcher.as_ref();
        let first_streamed = self.streamer.as_ref().map_or(usize::MAX, |s| s.first);
        for (local_l, &ly) in self.layers.iter().enumerate() {
            let global_l = self.layer_range.start + local_l;
            let streamed = match self.streamer.as_mut() {
                Some(st) if global_l >= st.first => Some(st.take(global_l).expect("reading a layer from the model file failed")),
                _ => None,
            };
            let lbase = match (&streamed, &self.layer_spans) {
                (Some(buf), Some(spans)) => buf.as_ptr().wrapping_sub(spans[global_l].0),
                _ => base,
            };
            if let (Some(pf), Some(next)) = (hint.filter(|_| global_l + 1 < first_streamed), self.layers.get(local_l + 1)) {
                let mut r = vec![span(&next.wq), span(&next.wk), span(&next.wv), span(&next.wo)];
                match &next.ffn {
                    FfnKind::Dense(f) => r.extend(f.spans()),
                    FfnKind::Moe(m) => r.push(span(&m.router)),
                }
                pf.hint(r);
            }

            let scale = c.attn_scale.unwrap_or(1.0 / (c.head_dim as f32).sqrt());
            for b in 0..bsz {
                rmsnorm(&xs[b], f32_at(lbase, ly.attn_norm, c.dim), &mut x_norms[b], c.rms_eps);
            }
            {
                // Q/K/V for the whole batch: each projection's weights are decoded once.
                let xr = as_refs(&x_norms);
                matvec_multi(pool, lbase, &ly.wq, &xr, &mut as_muts(&mut qs));
                matvec_multi(pool, lbase, &ly.wk, &xr, &mut as_muts(&mut ks));
                matvec_multi(pool, lbase, &ly.wv, &xr, &mut as_muts(&mut vs));
            }
            // K/V of every batch token are written before any attention runs; token b only
            // reads positions <= its own, so causality is unchanged.
            for b in 0..bsz {
                let pos = start_pos + b;
                let (q, k, v) = (&mut qs[b], &mut ks[b], &mut vs[b]);
                add_bias(lbase, q, ly.q_bias);
                add_bias(lbase, k, ly.k_bias);
                add_bias(lbase, v, ly.v_bias);
                if let Some(off) = ly.q_norm {
                    let n = if ly.qk_norm_full { c.q_dim } else { c.head_dim };
                    rmsnorm_heads(q, f32_at(lbase, off, n), n, c.rms_eps);
                }
                if let Some(off) = ly.k_norm {
                    let n = if ly.qk_norm_full { c.kv_dim } else { c.head_dim };
                    rmsnorm_heads(k, f32_at(lbase, off, n), n, c.rms_eps);
                }
                self.rope.rotate(q, c.head_dim, pos as f32);
                self.rope.rotate(k, c.head_dim, pos as f32);

                let kv_off = (local_l * self.max_seq + pos) * c.kv_dim;
                f32_to_f16_slice(k, &mut self.k_cache[kv_off..kv_off + c.kv_dim]);
                f32_to_f16_slice(v, &mut self.v_cache[kv_off..kv_off + c.kv_dim]);
            }

            for b in 0..bsz {
                let pos = start_pos + b;
                let q = &qs[b];
                let attn_out = &mut attn_outs[b];
                let n_heads = c.n_heads;
                let head_dim = c.head_dim;
                let kv_dim = c.kv_dim;
                let heads_per_kv = c.n_heads / c.n_kv_heads;
                let n_vec = head_dim / 8;
                let max_seq = self.max_seq;
                let q_addr = q.as_ptr() as usize;
                let k_addr = self.k_cache.as_ptr() as usize;
                let v_addr = self.v_cache.as_ptr() as usize;
                let out_addr = attn_out.as_mut_ptr() as usize;

                let compute_head_fn = |h: usize| unsafe {
                    let kvh = h / heads_per_kv;
                    let q_head = (q_addr as *const f32).add(h * head_dim);
                    let out_head = (out_addr as *mut f32).add(h * head_dim);

                    let mut m_prev = f32::NEG_INFINITY;
                    let mut l_prev = 0.0f32;
                    let mut acc_v = [_mm256_setzero_ps(); 16];

                    for t in 0..=pos {
                        let t_off = (local_l * max_seq + t) * kv_dim + kvh * head_dim;
                        let k_head = (k_addr as *const u16).add(t_off);
                        let v_head = (v_addr as *const u16).add(t_off);

                        let score = dot_f16_row_avx2(k_head as *const u8, q_head, head_dim) * scale;
                        let m_new = m_prev.max(score);
                        let alpha = (m_prev - m_new).exp();
                        let p = (score - m_new).exp();
                        l_prev = l_prev * alpha + p;
                        m_prev = m_new;

                        let (va, vp) = (_mm256_set1_ps(alpha), _mm256_set1_ps(p));
                        for d in 0..n_vec {
                            let ov = _mm256_mul_ps(acc_v[d], va);
                            let vv = _mm256_cvtph_ps(_mm_loadu_si128(v_head.add(d * 8) as *const __m128i));
                            acc_v[d] = _mm256_fmadd_ps(vp, vv, ov);
                        }
                    }
                    let inv_l = _mm256_set1_ps(1.0f32 / l_prev.max(1e-9));
                    for d in 0..n_vec {
                        _mm256_storeu_ps(out_head.add(d * 8), _mm256_mul_ps(acc_v[d], inv_l));
                    }
                };

                if let Some(p) = pool {
                    if p.n_threads() > 1 && n_heads >= p.n_threads() {
                        p.run(&|t, n| {
                            let h0 = n_heads * t / n;
                            let h1 = n_heads * (t + 1) / n;
                            for h in h0..h1 {
                                compute_head_fn(h);
                            }
                        });
                    } else {
                        for h in 0..n_heads {
                            compute_head_fn(h);
                        }
                    }
                } else {
                    for h in 0..n_heads {
                        compute_head_fn(h);
                    }
                }

            }

            matvec_multi(pool, lbase, &ly.wo, &as_refs(&attn_outs), &mut as_muts(&mut proj_outs));
            for b in 0..bsz {
                for i in 0..c.dim {
                    xs[b][i] += c.residual_scale * proj_outs[b][i];
                }
                rmsnorm(&xs[b], f32_at(lbase, ly.ffn_norm, c.dim), &mut x_norms[b], c.rms_eps);
            }

            match &ly.ffn {
                FfnKind::Dense(f) => {
                    ffn_forward_multi(pool, lbase, f, &as_refs(&x_norms), &mut as_muts(&mut proj_outs), &mut ffn_scratch);
                }
                FfnKind::Moe(m) => moe_forward_batch(
                    pool,
                    lbase,
                    m,
                    &x_norms,
                    &mut proj_outs,
                    Some((&mut self.moe_stats, global_l)),
                    hint,
                    self.expert_cache.as_mut(),
                ),
            }
            for b in 0..bsz {
                for i in 0..c.dim {
                    xs[b][i] += c.residual_scale * proj_outs[b][i];
                }
            }
            if let (Some(buf), Some(st)) = (streamed, self.streamer.as_mut()) {
                st.give_back(buf);
            }
        }

        if self.layer_range.end == self.cfg.n_layers {
            for b in 0..bsz {
                rmsnorm(&xs[b], f32_at(base, self.output_norm, c.dim), &mut x_norms[b], c.rms_eps);
            }
            x_norms
        } else {
            xs
        }
    }

    /// Evaluates this engine's assigned layer partition (`self.layer_range`).
    /// - If `token_id` is Some, initializes `x` from the embedding table (Stage 0 / Worker).
    /// - If `in_hidden` is Some, uses the provided activation vector from the previous stage.
    /// - Evaluates `self.layers`, storing local keys/values in `k_cache`/`v_cache`.
    /// - If `self.layer_range.end == self.cfg.n_layers`, applies `output_norm` and returns normalized hidden state.
    /// - Otherwise, returns the un-normalized residual hidden state ready for the next node.
    #[target_feature(enable = "avx2,fma,f16c")]
    pub unsafe fn forward_slice(
        &mut self,
        token_id: Option<usize>,
        in_hidden: Option<&[f32]>,
        pos: usize,
    ) -> Vec<f32> {
        let c = self.cfg;
        let base = self.raw_bytes.as_ptr();
        let pool = self.pool.as_ref();

        let mut x = if let Some(tid) = token_id {
            let rb = row_bytes(self.embed.dtype, c.dim).expect("unsupported embedding type");
            let row = std::slice::from_raw_parts(base.add(self.embed.offset + tid * rb), rb);
            let mut val = dequant_row(self.embed.dtype, row, c.dim);
            if c.embedding_scale != 1.0 {
                val.iter_mut().for_each(|v| *v *= c.embedding_scale);
            }
            val
        } else if let Some(h) = in_hidden {
            h.to_vec()
        } else {
            panic!("forward_slice requires token_id or in_hidden");
        };

        let mut x_norm = vec![0.0f32; c.dim];
        let mut q = vec![0.0f32; c.q_dim];
        let mut k = vec![0.0f32; c.kv_dim];
        let mut v = vec![0.0f32; c.kv_dim];
        let mut attn_out = vec![0.0f32; c.q_dim];
        let mut proj_out = vec![0.0f32; c.dim];
        let mut moe_tmp = vec![0.0f32; c.dim];
        if self.is_moe() {
            self.moe_stats.tokens += 1;
        }

        let hint = self.prefetcher.as_ref();
        let first_streamed = self.streamer.as_ref().map_or(usize::MAX, |s| s.first);
        for (local_l, &ly) in self.layers.iter().enumerate() {
            let global_l = self.layer_range.start + local_l;
            let streamed = match self.streamer.as_mut() {
                Some(st) if global_l >= st.first => Some(st.take(global_l).expect("reading a layer from the model file failed")),
                _ => None,
            };
            let lbase = match (&streamed, &self.layer_spans) {
                (Some(buf), Some(spans)) => buf.as_ptr().wrapping_sub(spans[global_l].0),
                _ => base,
            };
            if let (Some(pf), Some(next)) = (hint.filter(|_| global_l + 1 < first_streamed), self.layers.get(local_l + 1)) {
                let mut r = vec![span(&next.wq), span(&next.wk), span(&next.wv), span(&next.wo)];
                match &next.ffn {
                    FfnKind::Dense(f) => r.extend(f.spans()),
                    FfnKind::Moe(m) => r.push(span(&m.router)),
                }
                pf.hint(r);
            }

            // Attention: norm, Q/K/V (+ bias), optional per-head Q/K norm, RoPE.
            rmsnorm(&x, f32_at(lbase, ly.attn_norm, c.dim), &mut x_norm, c.rms_eps);
            matvec(pool, lbase, &ly.wq, &x_norm, &mut q);
            matvec(pool, lbase, &ly.wk, &x_norm, &mut k);
            matvec(pool, lbase, &ly.wv, &x_norm, &mut v);
            add_bias(lbase, &mut q, ly.q_bias);
            add_bias(lbase, &mut k, ly.k_bias);
            add_bias(lbase, &mut v, ly.v_bias);
            if let Some(off) = ly.q_norm {
                let n = if ly.qk_norm_full { c.q_dim } else { c.head_dim };
                rmsnorm_heads(&mut q, f32_at(lbase, off, n), n, c.rms_eps);
            }
            if let Some(off) = ly.k_norm {
                let n = if ly.qk_norm_full { c.kv_dim } else { c.head_dim };
                rmsnorm_heads(&mut k, f32_at(lbase, off, n), n, c.rms_eps);
            }
            self.rope.rotate(&mut q, c.head_dim, pos as f32);
            self.rope.rotate(&mut k, c.head_dim, pos as f32);

            let kv_off = (local_l * self.max_seq + pos) * c.kv_dim;
            f32_to_f16_slice(&k, &mut self.k_cache[kv_off..kv_off + c.kv_dim]);
            f32_to_f16_slice(&v, &mut self.v_cache[kv_off..kv_off + c.kv_dim]);

            // Grouped-query attention with an online softmax over positions 0..=pos.
            let scale = c.attn_scale.unwrap_or(1.0 / (c.head_dim as f32).sqrt());
            let n_heads = c.n_heads;
            let head_dim = c.head_dim;
            let kv_dim = c.kv_dim;
            let heads_per_kv = c.n_heads / c.n_kv_heads;
            let n_vec = head_dim / 8;
            let max_seq = self.max_seq;
            let q_addr = q.as_ptr() as usize;
            let k_addr = self.k_cache.as_ptr() as usize;
            let v_addr = self.v_cache.as_ptr() as usize;
            let out_addr = attn_out.as_mut_ptr() as usize;

            let compute_head_fn = |h: usize| unsafe {
                let kvh = h / heads_per_kv;
                let q_head = (q_addr as *const f32).add(h * head_dim);
                let out_head = (out_addr as *mut f32).add(h * head_dim);

                let mut m_prev = f32::NEG_INFINITY;
                let mut l_prev = 0.0f32;
                let mut acc_v = [_mm256_setzero_ps(); 16];

                for t in 0..=pos {
                    let t_off = (local_l * max_seq + t) * kv_dim + kvh * head_dim;
                    let k_head = (k_addr as *const u16).add(t_off);
                    let v_head = (v_addr as *const u16).add(t_off);

                    let score = dot_f16_row_avx2(k_head as *const u8, q_head, head_dim) * scale;
                    let m_new = m_prev.max(score);
                    let alpha = (m_prev - m_new).exp();
                    let p = (score - m_new).exp();
                    l_prev = l_prev * alpha + p;
                    m_prev = m_new;

                    let (va, vp) = (_mm256_set1_ps(alpha), _mm256_set1_ps(p));
                    for d in 0..n_vec {
                        let ov = _mm256_mul_ps(acc_v[d], va);
                        let vv = _mm256_cvtph_ps(_mm_loadu_si128(v_head.add(d * 8) as *const __m128i));
                        acc_v[d] = _mm256_fmadd_ps(vp, vv, ov);
                    }
                }
                let inv_l = _mm256_set1_ps(1.0f32 / l_prev.max(1e-9));
                for d in 0..n_vec {
                    _mm256_storeu_ps(out_head.add(d * 8), _mm256_mul_ps(acc_v[d], inv_l));
                }
            };

            if let Some(p) = pool {
                if p.n_threads() > 1 && n_heads >= p.n_threads() {
                    p.run(&|t, n| {
                        let h0 = n_heads * t / n;
                        let h1 = n_heads * (t + 1) / n;
                        for h in h0..h1 {
                            compute_head_fn(h);
                        }
                    });
                } else {
                    for h in 0..n_heads {
                        compute_head_fn(h);
                    }
                }
            } else {
                for h in 0..n_heads {
                    compute_head_fn(h);
                }
            }

            matvec(pool, lbase, &ly.wo, &attn_out, &mut proj_out);
            for i in 0..c.dim {
                x[i] += c.residual_scale * proj_out[i];
            }

            // Feed-forward: dense SwiGLU or mixture of experts.
            rmsnorm(&x, f32_at(lbase, ly.ffn_norm, c.dim), &mut x_norm, c.rms_eps);
            match &ly.ffn {
                FfnKind::Dense(f) => ffn_forward(pool, lbase, f, &x_norm, &mut proj_out),
                FfnKind::Moe(m) => moe_forward(
                    pool,
                    lbase,
                    m,
                    &x_norm,
                    &mut proj_out,
                    Some((&mut self.moe_stats, global_l)),
                    hint,
                    self.expert_cache.as_mut(),
                    &mut moe_tmp,
                ),
            }
            for i in 0..c.dim {
                x[i] += c.residual_scale * proj_out[i];
            }
            if let (Some(buf), Some(st)) = (streamed, self.streamer.as_mut()) {
                st.give_back(buf);
            }
        }

        if self.layer_range.end == self.cfg.n_layers {
            rmsnorm(&x, f32_at(base, self.output_norm, c.dim), &mut x_norm, c.rms_eps);
            x_norm
        } else {
            x
        }
    }

    /// Evaluates all assigned layers for `token_id` at `pos`.
    #[inline]
    pub unsafe fn forward_hidden(&mut self, token_id: usize, pos: usize) -> Vec<f32> {
        self.forward_slice(Some(token_id), None, pos)
    }

    /// Computes LM-head logits for `hidden` and picks the next token using `self.sampler`:
    /// repetition penalty, temperature, top-k, min-p, top-p, then a seeded random draw
    /// (or plain argmax when `temperature <= 0`). If `forbid_stop` is set, stop tokens are
    /// masked so the reply can't be empty. If `forbid_think` is set, opening `<think>` is masked.
    #[target_feature(enable = "avx2,fma")]
    pub unsafe fn sample_next_token(
        &mut self,
        hidden: &[f32],
        recent: &[usize],
        forbid_stop: bool,
        forbid_think: bool,
    ) -> usize {
        let c = self.cfg;
        if self.logits_buf.len() != c.vocab {
            self.logits_buf.resize(c.vocab, 0.0);
        }
        if self.penalized_mask.len() != c.vocab {
            self.penalized_mask.resize(c.vocab, 0);
        }
        let t = std::time::Instant::now();
        matvec(self.pool.as_ref(), self.raw_bytes.as_ptr(), &self.lm_head, hidden, &mut self.logits_buf);
        self.timing.head_us += us_since(t);
        let t = std::time::Instant::now();
        let tok = self.sample_from_logits(recent, forbid_stop, forbid_think);
        self.timing.sample_us += us_since(t);
        tok
    }

    /// LM-head logits for every hidden state of a verify batch in ONE shared-decode pass over
    /// the (151,936-row) output matrix, into `batch_logits[i * vocab..]`.
    #[target_feature(enable = "avx2,fma")]
    unsafe fn compute_logits_batch(&mut self, hiddens: &[Vec<f32>]) {
        let vocab = self.cfg.vocab;
        let need = hiddens.len() * vocab;
        if self.batch_logits.len() < need {
            self.batch_logits.resize(need, 0.0);
        }
        let t = std::time::Instant::now();
        let xr = as_refs(hiddens);
        let mut outs: Vec<&mut [f32]> = self.batch_logits[..need].chunks_mut(vocab).collect();
        matvec_multi(self.pool.as_ref(), self.raw_bytes.as_ptr(), &self.lm_head, &xr, &mut outs);
        self.timing.head_us += us_since(t);
    }

    /// Samples from row `i` of `batch_logits` with exactly the same rules (and RNG draw) as
    /// `sample_next_token`.
    #[target_feature(enable = "avx2,fma")]
    unsafe fn sample_from_batch(&mut self, i: usize, recent: &[usize], forbid_stop: bool, forbid_think: bool) -> usize {
        let vocab = self.cfg.vocab;
        if self.logits_buf.len() != vocab {
            self.logits_buf.resize(vocab, 0.0);
        }
        if self.penalized_mask.len() != vocab {
            self.penalized_mask.resize(vocab, 0);
        }
        let t = std::time::Instant::now();
        self.logits_buf.copy_from_slice(&self.batch_logits[i * vocab..(i + 1) * vocab]);
        let tok = self.sample_from_logits(recent, forbid_stop, forbid_think);
        self.timing.sample_us += us_since(t);
        tok
    }

    /// The sampling half of `sample_next_token`, on logits already in `logits_buf`.
    #[target_feature(enable = "avx2,fma")]
    unsafe fn sample_from_logits(&mut self, recent: &[usize], forbid_stop: bool, forbid_think: bool) -> usize {
        let c = self.cfg;
        if c.logit_scale != 1.0 {
            self.logits_buf.iter_mut().for_each(|l| *l /= c.logit_scale);
        }

        let sc = self.sampler;
        if sc.repeat_penalty != 1.0 {
            for &t in recent {
                if t < self.logits_buf.len() && self.penalized_mask[t] == 0 {
                    self.penalized_mask[t] = 1;
                    let logit = &mut self.logits_buf[t];
                    *logit = if *logit > 0.0 { *logit / sc.repeat_penalty } else { *logit * sc.repeat_penalty };
                }
            }
            // Clear only the touched entries
            for &t in recent {
                if t < self.penalized_mask.len() {
                    self.penalized_mask[t] = 0;
                }
            }
        }
        if forbid_stop {
            for &id in &self.stop_ids {
                if id < self.logits_buf.len() {
                    self.logits_buf[id] = f32::NEG_INFINITY;
                }
            }
        }
        if forbid_think {
            if let Some((open, _)) = self.think_ids {
                if open < self.logits_buf.len() {
                    self.logits_buf[open] = f32::NEG_INFINITY;
                }
            }
        }

        let argmax = |logits: &[f32]| {
            logits
                .iter()
                .enumerate()
                .max_by(|a, b| a.1.total_cmp(b.1))
                .map(|(i, _)| i)
                .unwrap_or(0)
        };
        if sc.temperature <= 0.0 {
            return argmax(&self.logits_buf);
        }

        // Candidates: top-k by logit (reusing pre-allocated cand_buf).
        self.cand_buf.clear();
        self.cand_buf.extend((0..c.vocab).filter(|&t| self.logits_buf[t].is_finite()));
        let k = if sc.top_k == 0 { self.cand_buf.len() } else { sc.top_k.min(self.cand_buf.len()) };
        if k == 0 {
            return argmax(&self.logits_buf);
        }
        let logits = &self.logits_buf;
        if k < self.cand_buf.len() {
            self.cand_buf.select_nth_unstable_by(k - 1, |&a, &b| logits[b].total_cmp(&logits[a]));
            self.cand_buf.truncate(k);
        }
        self.cand_buf.sort_unstable_by(|&a, &b| logits[b].total_cmp(&logits[a]));

        // Softmax with temperature (subtract max for numerical stability).
        let cand = &self.cand_buf;
        let max = logits[cand[0]];
        let mut stack_probs = [0.0f32; 128];
        let mut heap_probs;
        let probs: &mut [f32] = if k <= 128 {
            for i in 0..k {
                stack_probs[i] = ((logits[cand[i]] - max) / sc.temperature).exp();
            }
            &mut stack_probs[..k]
        } else {
            heap_probs = cand.iter().map(|&t| ((logits[t] - max) / sc.temperature).exp()).collect::<Vec<f32>>();
            &mut heap_probs[..]
        };
        let sum: f32 = probs.iter().sum();
        probs.iter_mut().for_each(|p| *p /= sum);

        // min-p, then top-p (nucleus). Both keep at least the best token.
        let floor = sc.min_p * probs[0];
        let mut keep = probs.iter().take_while(|&&p| p >= floor).count().max(1);
        let mut cum = 0.0f32;
        for (i, &p) in probs[..keep].iter().enumerate() {
            cum += p;
            if cum >= sc.top_p {
                keep = i + 1;
                break;
            }
        }

        // Sample from the renormalized survivors.
        let total: f32 = probs[..keep].iter().sum();
        let mut r = self.rng.next_f32() * total;
        for i in 0..keep {
            r -= probs[i];
            if r <= 0.0 {
                return cand[i];
            }
        }
        cand[keep - 1]
    }

    /// The system message, framed for this model.
    fn encode_system(&self) -> Vec<usize> {
        let f = &self.format;
        if self.system_prompt.trim().is_empty() {
            return Vec::new();
        }
        [&f.system_open[..], &self.encode_bpe_segment(&self.system_prompt), &f.system_close].concat()
    }

    /// Pre-warms and feeds the system prompt into the KV-cache so initial turns respond instantly.
    pub unsafe fn prefill_system(&mut self) {
        self.prefill_system_with(&mut |_, _| {});
    }

    /// `prefill_system`, calling `progress(done, total)` (in tokens) after every chunk.
    /// Returns true when the KV entries came from the on-disk prompt cache instead of being
    /// computed (see `load_prompt_kv`). On a miss the prompt is computed and then saved.
    pub unsafe fn prefill_system_with(&mut self, progress: &mut dyn FnMut(usize, usize)) -> bool {
        if self.n_keep == 0 {
            let sys = self.encode_system();
            if !sys.is_empty() {
                // The cache covers this engine and the worker; a draft model would need its own.
                let cacheable = self.draft_engine.is_none()
                    && sys.len() <= self.max_seq
                    && std::env::var("SPINDLE_NO_PROMPT_CACHE").map_or(true, |v| v != "1");
                let key = self.prompt_cache_key(&sys);
                if cacheable {
                    let local = self.load_prompt_kv(key, &sys).unwrap_or(false);
                    let worker = match self.cluster_client.as_mut() {
                        None => true,
                        Some(c) => c.prompt_cache(crate::cluster_net::PROMPT_CACHE_LOAD, key, &sys) == Some(true),
                    };
                    if local && worker {
                        progress(sys.len(), sys.len());
                        return true;
                    }
                    // A partial hit is no use: compute everything (this overwrites both sides).
                    self.cur_pos = 0;
                    self.n_keep = 0;
                }
                let mut done = 0;
                progress(0, sys.len());
                for chunk in sys.chunks(128) {
                    self.feed(chunk);
                    if let Some(draft) = self.draft_engine.as_mut() {
                        draft.feed(chunk);
                    }
                    done += chunk.len();
                    progress(done, sys.len());
                }
                if let Some(draft) = self.draft_engine.as_mut() {
                    draft.n_keep = self.cur_pos;
                }
                self.n_keep = self.cur_pos;
                if cacheable {
                    if let Err(e) = self.save_prompt_kv(key, &sys) {
                        crate::vlog!("[prompt-cache] not saved: {e}");
                    }
                    if let Some(c) = self.cluster_client.as_mut() {
                        let _ = c.prompt_cache(crate::cluster_net::PROMPT_CACHE_SAVE, key, &sys);
                    }
                }
            }
        }
        false
    }

    /// Identifies a cached system prompt: everything that changes its KV entries on this
    /// node or the worker (spindle version, model file, layer split, MoE pruning, wire
    /// format, the prompt tokens). Any difference gives a different key, so a stale cache is
    /// never used.
    pub fn prompt_cache_key(&self, tokens: &[usize]) -> u64 {
        let mut h = Fnv64::new();
        h.bytes(env!("CARGO_PKG_VERSION").as_bytes());
        h.u64(PROMPT_CACHE_VERSION as u64);
        h.bytes(self.idx.model_name.as_bytes());
        h.u64(self.raw_bytes.len() as u64);
        h.u64(self.cfg.n_layers as u64);
        h.u64(self.cfg.kv_dim as u64);
        h.u64(self.moe_prune().to_bits() as u64);
        if let Some(c) = self.cluster_client.as_ref() {
            h.u64(c.wire_format as u64);
            h.u64(c.worker_range.0 as u64);
            h.u64(c.worker_range.1 as u64);
        }
        h.u64(self.layer_range.start as u64);
        h.u64(self.layer_range.end as u64);
        for &t in tokens {
            h.u64(t as u64);
        }
        h.finish()
    }

    /// `<model>.kv-<layers>.bin`: one prompt cache file per layer range, next to the model.
    fn prompt_cache_path(&self) -> std::path::PathBuf {
        std::path::PathBuf::from(format!("{}.kv-{}-{}.bin", self.path, self.layer_range.start, self.layer_range.end))
    }

    /// Writes the KV entries of positions `0..tokens.len()` for this node's layers. The file
    /// is replaced atomically (written to a temp name, then renamed), so a crash mid-write
    /// can't leave a half file behind.
    pub fn save_prompt_kv(&self, key: u64, tokens: &[usize]) -> std::io::Result<()> {
        use std::io::Write;
        let key = mix_key(key, self.resident_hash());
        let n = tokens.len();
        let kv = self.cfg.kv_dim;
        if n == 0 || n > self.max_seq || self.cur_pos < n {
            return Err(Error::new(ErrorKind::InvalidInput, "prompt not fully in the cache"));
        }
        let path = self.prompt_cache_path();
        let tmp = path.with_extension("bin.tmp");
        let mut f = std::io::BufWriter::new(std::fs::File::create(&tmp)?);
        f.write_all(PROMPT_CACHE_MAGIC)?;
        for v in [PROMPT_CACHE_VERSION as u64, key, n as u64, self.layers.len() as u64, kv as u64] {
            f.write_all(&v.to_le_bytes())?;
        }
        for &t in tokens {
            f.write_all(&(t as u32).to_le_bytes())?;
        }
        for cache in [&self.k_cache, &self.v_cache] {
            for l in 0..self.layers.len() {
                let start = l * self.max_seq * kv;
                let part = &cache[start..start + n * kv];
                // SAFETY: u16 has no padding; little-endian on x86-64.
                let bytes = unsafe { std::slice::from_raw_parts(part.as_ptr() as *const u8, part.len() * 2) };
                f.write_all(bytes)?;
            }
        }
        f.flush()?;
        drop(f);
        std::fs::rename(&tmp, &path)?;
        crate::vlog!("[prompt-cache] saved {n} tokens to {}", path.display());
        Ok(())
    }

    /// Fills positions `0..tokens.len()` from the prompt cache file if it was saved with the
    /// same `key` and the same tokens. Returns false (and changes nothing) otherwise.
    pub fn load_prompt_kv(&mut self, key: u64, tokens: &[usize]) -> std::io::Result<bool> {
        use std::io::Read;
        let key = mix_key(key, self.resident_hash());
        let n = tokens.len();
        let kv = self.cfg.kv_dim;
        if n == 0 || n > self.max_seq {
            return Ok(false);
        }
        let path = self.prompt_cache_path();
        let Ok(file) = std::fs::File::open(&path) else { return Ok(false) };
        let mut f = std::io::BufReader::new(file);
        let mut magic = [0u8; 4];
        f.read_exact(&mut magic)?;
        let mut hdr = [0u64; 5];
        for v in hdr.iter_mut() {
            let mut b = [0u8; 8];
            f.read_exact(&mut b)?;
            *v = u64::from_le_bytes(b);
        }
        if &magic != PROMPT_CACHE_MAGIC
            || hdr != [PROMPT_CACHE_VERSION as u64, key, n as u64, self.layers.len() as u64, kv as u64]
        {
            return Ok(false);
        }
        let mut tb = vec![0u8; n * 4];
        f.read_exact(&mut tb)?;
        if tb.chunks_exact(4).map(|c| u32::from_le_bytes(c.try_into().unwrap()) as usize).ne(tokens.iter().copied()) {
            return Ok(false);
        }
        // Read everything before touching the live cache, so a short file changes nothing.
        let per_layer = n * kv;
        let mut data = vec![0u16; 2 * self.layers.len() * per_layer];
        {
            // SAFETY: plain u16 buffer viewed as bytes.
            let bytes = unsafe { std::slice::from_raw_parts_mut(data.as_mut_ptr() as *mut u8, data.len() * 2) };
            f.read_exact(bytes)?;
        }
        let n_layers = self.layers.len();
        for (ci, cache) in [&mut self.k_cache, &mut self.v_cache].into_iter().enumerate() {
            for l in 0..n_layers {
                let src = &data[(ci * n_layers + l) * per_layer..(ci * n_layers + l + 1) * per_layer];
                let start = l * self.max_seq * kv;
                cache[start..start + per_layer].copy_from_slice(src);
            }
        }
        self.cur_pos = n;
        self.n_keep = n;
        self.remember_tokens(tokens);
        crate::vlog!("[prompt-cache] loaded {n} tokens from {}", path.display());
        Ok(true)
    }

    /// A user message followed by the opening of the assistant's reply.
    fn encode_user_turn(&self, user_prompt: &str, allow_think: bool) -> Vec<usize> {
        let f = &self.format;
        let mut ids = [&f.user_open[..], &self.encode_bpe_segment(user_prompt.trim()), &f.user_close, &f.assistant_open].concat();
        if !allow_think {
            if let Some((open, close)) = self.think_ids {
                // Official Qwen/R1 fast mode: inject a closed think block (<think>\n\n</think>\n\n)
                // so the model recognizes reasoning is already done and immediately begins the direct answer.
                ids.push(open);
                ids.extend(self.encode_bpe_segment("\n\n"));
                ids.push(close);
                ids.extend(self.encode_bpe_segment("\n\n"));
            }
        }
        ids
    }

    /// Full prompt for a single message (system + user + assistant header).
    pub fn encode_chatml(&self, user_prompt: &str) -> Vec<usize> {
        let mut ids = self.encode_system();
        ids.extend(self.encode_user_turn(user_prompt, false));
        ids
    }

    fn encode_bpe_segment(&self, text: &str) -> Vec<usize> {
        // Split text into GPT-2 pre-tokenization words (preserving leading space on words,
        // keeping newlines separate, and stripping '\r').
        let mut clean = String::with_capacity(text.len());
        for ch in text.chars() {
            if ch != '\r' {
                clean.push(ch);
            }
        }

        let qwen2 = matches!(self.idx.metadata.get("tokenizer.ggml.pre"), Some(GgufValue::String(p)) if p == "qwen2");
        // Pre-split into chunks: each newline is its own chunk; spaces attach to the following word
        let mut chunks: Vec<String> = Vec::new();
        let mut cur = String::new();
        if qwen2 {
            chunks = pretokenize_qwen2(&clean)
                .into_iter()
                .map(|w| w.bytes().map(|b| self.byte_enc[b as usize]).collect())
                .collect();
        }
        for ch in clean.chars().filter(|_| !qwen2) {
            if ch == '\n' {
                if !cur.is_empty() {
                    chunks.push(std::mem::take(&mut cur));
                }
                chunks.push("\u{010A}".to_string());
            } else if ch == ' ' {
                if !cur.is_empty() && !cur.ends_with('\u{0120}') {
                    chunks.push(std::mem::take(&mut cur));
                }
                cur.push('\u{0120}');
            } else {
                // Separate punctuation from alphanumeric runs just like GPT-2 regex
                let is_punct = ch.is_ascii_punctuation();
                let prev_is_punct = cur
                    .chars()
                    .last()
                    .map(|p| p != '\u{0120}' && p.is_ascii_punctuation())
                    .unwrap_or(false);
                let prev_has_alnum = cur
                    .chars()
                    .last()
                    .map(|p| p != '\u{0120}' && !p.is_ascii_punctuation())
                    .unwrap_or(false);
                if (is_punct && prev_has_alnum) || (!is_punct && prev_is_punct) {
                    chunks.push(std::mem::take(&mut cur));
                }
                // Byte-level BPE: every UTF-8 byte maps to one vocab-alphabet char.
                let mut buf = [0u8; 4];
                for &b in ch.encode_utf8(&mut buf).as_bytes() {
                    cur.push(self.byte_enc[b as usize]);
                }
            }
        }
        if !cur.is_empty() {
            chunks.push(cur);
        }

        let mut out = Vec::new();
        for word in chunks {
            // Fast path: if the whole pre-tokenized word is already a single vocab token, emit it.
            if let Some(&tid) = self.idx.token_to_id.get(&word) {
                out.push(tid);
                continue;
            }

            // Otherwise run canonical BPE merge loop using `bpe_ranks`
            let mut parts: Vec<String> = word.chars().map(|c| c.to_string()).collect();
            while parts.len() >= 2 {
                let mut best_pair_idx = None;
                let mut best_rank = usize::MAX;
                for i in 0..(parts.len() - 1) {
                    if let Some(&rank) = self
                        .idx
                        .bpe_ranks
                        .get(&(parts[i].clone(), parts[i + 1].clone()))
                    {
                        if rank < best_rank {
                            best_rank = rank;
                            best_pair_idx = Some(i);
                        }
                    }
                }
                if let Some(i) = best_pair_idx {
                    let merged = format!("{}{}", parts[i], parts[i + 1]);
                    parts[i] = merged;
                    parts.remove(i + 1);
                } else {
                    break;
                }
            }

            for p in parts {
                if let Some(&tid) = self.idx.token_to_id.get(&p) {
                    out.push(tid);
                }
            }
        }
        out
    }

    /// Raw bytes of a token (vocab strings use the GPT-2 byte alphabet). A multi-byte UTF-8
    /// character can be split across tokens, so callers join bytes before decoding.
    pub fn token_bytes(&self, tid: usize) -> Vec<u8> {
        let raw = self.idx.vocab.get(tid).map(String::as_str).unwrap_or("");
        let mut out = Vec::with_capacity(raw.len());
        for ch in raw.chars() {
            match self.byte_dec.get(&ch) {
                Some(&b) => out.push(b),
                None => {
                    let mut buf = [0u8; 4];
                    out.extend_from_slice(ch.encode_utf8(&mut buf).as_bytes());
                }
            }
        }
        out
    }

    /// Plain text completion with no chat framing, for comparing against llama.cpp: encodes
    /// `prompt` (with BOS if the model wants one), then generates up to `n` tokens.
    pub unsafe fn complete_raw(&mut self, prompt: &str, n: usize, on_text: &mut dyn FnMut(&str)) -> usize {
        self.reset_kv();
        let mut ids: Vec<usize> = self.bos.into_iter().collect();
        ids.extend(self.encode_bpe_segment(prompt));
        crate::vlog!("[raw] prompt tokens: {ids:?}");
        let mut hidden = self.feed(&ids);
        let mut recent = Vec::new();
        let mut pending: Vec<u8> = Vec::new();
        for _ in 0..n {
            if crate::ui::verbose() {
                // The two best candidates and their logit gap: a tiny gap means another engine
                // can legitimately pick the other one because of rounding.
                let mut logits = vec![0.0f32; self.cfg.vocab];
                matvec(self.pool.as_ref(), self.raw_bytes.as_ptr(), &self.lm_head, &hidden, &mut logits);
                let mut idx: Vec<usize> = (0..logits.len()).collect();
                idx.select_nth_unstable_by(1, |&a, &b| logits[b].total_cmp(&logits[a]));
                let (a, b) = if logits[idx[0]] >= logits[idx[1]] { (idx[0], idx[1]) } else { (idx[1], idx[0]) };
                let s = |t: usize| String::from_utf8_lossy(&self.token_bytes(t)).into_owned();
                crate::vlog!(
                    "[raw] step {}: {:?} {:.3} vs {:?} {:.3} (gap {:.3})",
                    recent.len(),
                    s(a),
                    logits[a] / self.cfg.logit_scale,
                    s(b),
                    logits[b] / self.cfg.logit_scale,
                    (logits[a] - logits[b]) / self.cfg.logit_scale
                );
            }
            let next = self.sample_next_token(&hidden, &recent, false, false);
            if self.stop_ids.contains(&next) {
                break;
            }
            pending.extend(self.token_bytes(next));
            let valid = match std::str::from_utf8(&pending) {
                Ok(s) => s.len(),
                Err(e) if e.error_len().is_none() => e.valid_up_to(),
                Err(_) => pending.len(),
            };
            on_text(&String::from_utf8_lossy(&pending[..valid]));
            pending.drain(..valid);
            recent.push(next);
            hidden = self.feed(&[next]);
        }
        on_text(&String::from_utf8_lossy(&pending));
        recent.len()
    }

    /// Generates a conversational reply to `user_prompt`, passing text to `on_text` as it is
    /// produced (whole UTF-8 characters only). The KV-cache persists across calls, so earlier
    /// turns stay in context; only the new user turn is prefilled. Call `reset_kv()` to start
    /// a fresh conversation. Returns `(reply, seconds, tokens processed)`.
    pub unsafe fn generate_reply(
        &mut self,
        user_prompt: &str,
        max_new_tokens: usize,
        allow_think: bool,
        on_text: &mut dyn FnMut(&str),
    ) -> (String, f64, usize) {
        let t0 = Instant::now();
        self.spec_stats = (0, 0, 0);
        let mut draft_engine = self.draft_engine.take();
        let mut prefill_tokens = 0u64;
        if self.n_keep == 0 {
            let sys = self.encode_system();
            prefill_tokens += sys.len() as u64;
            self.feed(&sys);
            self.n_keep = self.cur_pos;
            if let Some(draft) = draft_engine.as_mut() {
                draft.feed(&sys);
                draft.n_keep = self.n_keep;
            }
        }
        let mut turn_ids = self.encode_user_turn(user_prompt, allow_think);
        // A single turn can never be larger than the non-system window (leave room to reply).
        let max_turn = (self.max_seq - self.n_keep) / 2;
        if turn_ids.len() > max_turn {
            turn_ids.drain(..turn_ids.len() - max_turn);
        }
        prefill_tokens += turn_ids.len() as u64;
        let last_hidden = self.feed(&turn_ids);
        if let Some(draft) = draft_engine.as_mut() {
            draft.feed(&turn_ids);
        }
        self.timing.prefill_us += us_since(t0);
        self.timing.prefill_tokens += prefill_tokens;
        // Worker compute is measured over the generation passes only (prefill excluded).
        let worker_t0 = self.cluster_client.as_mut().and_then(|c| c.worker_timing());
        let reply_start = self.cur_pos;
        let shifts_before = self.kv_shifts;
        let t_gen = Instant::now();

        let mut recent = Vec::with_capacity(max_new_tokens);
        // Reasoning models: are we inside <think>, and where does the answer start in `recent`?
        let mut in_think = false;
        let mut answer_from: Option<usize> = None;
        let mut reply = String::new();
        // Bytes of a UTF-8 character that isn't complete yet.
        let mut pending: Vec<u8> = Vec::new();
        let mut generated = 0usize;
        let forbid_think = !allow_think;

        let should_stop = |gen: usize, recent_len: usize, ans_from: Option<usize>, _thinking: bool| -> bool {
            if let Some(from) = ans_from {
                recent_len.saturating_sub(from) >= max_new_tokens
            } else {
                gen >= max_new_tokens
            }
        };

        // Emits one committed token: think-state tracking, UTF-8 streaming, history.
        macro_rules! emit {
            ($tok:expr) => {{
                let t_emit = std::time::Instant::now();
                let tok: usize = $tok;
                match self.think_ids {
                    Some((open, _)) if tok == open => in_think = true,
                    Some((_, close)) if tok == close => {
                        in_think = false;
                        answer_from = Some(recent.len() + 1);
                    }
                    _ => {}
                }
                pending.extend(self.token_bytes(tok));
                let valid = match std::str::from_utf8(&pending) {
                    Ok(s) => s.len(),
                    Err(e) if e.error_len().is_none() => e.valid_up_to(),
                    Err(_) => pending.len(),
                };
                let piece = String::from_utf8_lossy(&pending[..valid]).into_owned();
                pending.drain(..valid);
                on_text(&piece);
                reply.push_str(&piece);
                recent.push(tok);
                generated += 1;
                self.remember_tokens(&[tok]);
                self.timing.emit_us += us_since(t_emit);
            }};
        }
        macro_rules! penalty_window {
            () => {
                &recent[answer_from.unwrap_or(0).min(recent.len())..]
            };
        }

        // Speculative loop. Invariant at the top: `tok` has been sampled but is NOT yet in the
        // KV cache; `self.cur_pos` is where it goes. Each iteration feeds `[tok, drafts..]` in
        // ONE batched pass (one cluster round trip), then samples every position in order with
        // the normal sampler and the same RNG draws as plain decoding, keeping the longest
        // prefix of drafts the model itself would have produced. The first mismatch (or the
        // bonus token after a full accept) becomes the next `tok`, so nothing is recomputed.
        let use_lookup = self.speculate && draft_engine.is_none();
        let draft_shifts = draft_engine.as_ref().map_or(0, |d| d.kv_shifts);
        // After a weak (2-gram) draft is rejected outright, skip weak drafts for a while
        // (doubling up to 16 tokens) so text with no repetition never pays for verify batches.
        // Strong (3+-gram) matches are always tried. After a fully accepted batch the next
        // draft may grow (up to 7, one 8-vector kernel pass) while the copy streak lasts.
        let (mut backoff, mut skip) = (0usize, 0usize);
        let mut k_dyn = self.draft_len;
        let mut unfed: Option<usize> = None;
        let mut tok = self.sample_next_token(&last_hidden, penalty_window!(), generated < 2 || in_think, forbid_think);
        loop {
            if self.abort_signal.as_ref().is_some_and(|s| s.load(std::sync::atomic::Ordering::Relaxed)) {
                break;
            }
            if self.stop_ids.contains(&tok) {
                break;
            }
            emit!(tok);
            if should_stop(generated, recent.len(), answer_from, in_think) {
                unfed = Some(tok);
                break;
            }

            let budget = if let Some(from) = answer_from {
                max_new_tokens.saturating_sub(recent.len().saturating_sub(from))
            } else {
                max_new_tokens.saturating_sub(generated)
            };
            let k = k_dyn.min(budget.saturating_sub(1));
            let mut draft: Vec<usize> = Vec::new();
            let t_draft = std::time::Instant::now();
            if k > 0 && (skip == 0 || use_lookup) {
                if let Some(d) = draft_engine.as_mut() {
                    if self.kv_shifts == shifts_before && d.kv_shifts == draft_shifts && d.cur_pos >= reply_start {
                        // Catch the draft model up on every committed token it has not seen
                        // (always includes `tok`), then let it autoregress `k` proposals.
                        let from = d.cur_pos - reply_start;
                        let mut h = Vec::new();
                        for &t in &recent[from.min(recent.len())..] {
                            d.ensure_kv_room(1);
                            h = d.forward_hidden(t, d.cur_pos);
                            d.cur_pos += 1;
                        }
                        if d.kv_shifts == draft_shifts && !h.is_empty() {
                            for j in 0..k {
                                let x = d.sample_next_token(&h, &[], false, forbid_think);
                                if d.stop_ids.contains(&x) {
                                    break;
                                }
                                draft.push(x);
                                if j + 1 < k {
                                    d.ensure_kv_room(1);
                                    h = d.forward_hidden(x, d.cur_pos);
                                    d.cur_pos += 1;
                                }
                            }
                        }
                    }
                } else if use_lookup {
                    let (d, ng) = self.lookup_draft(k);
                    if skip == 0 || ng > LOOKUP_MIN_NGRAM {
                        draft = d;
                    }
                }
            }
            self.timing.draft_us += us_since(t_draft);
            skip = skip.saturating_sub(1);

            if draft.is_empty() {
                self.ensure_kv_room(1);
                let pos = self.cur_pos;
                let h = self.step_token(tok, pos);
                self.cur_pos += 1;
                tok = self.sample_next_token(&h, penalty_window!(), generated < 2 || in_think, forbid_think);
                continue;
            }

            let mut batch = Vec::with_capacity(draft.len() + 1);
            batch.push(tok);
            batch.extend_from_slice(&draft);
            self.ensure_kv_room(batch.len());
            let start = self.cur_pos;
            let hiddens = self.verify_forward(&batch, start);
            self.compute_logits_batch(&hiddens);
            self.spec_stats.1 += draft.len();
            self.spec_stats.2 += 1;

            // Position i's logits predict batch[i + 1] (= draft[i]).
            let mut accepted = 0usize;
            let mut correction = None;
            let mut done = false;
            for (i, &d_tok) in draft.iter().enumerate() {
                let s = self.sample_from_batch(i, penalty_window!(), generated < 2 || in_think, forbid_think);
                if s != d_tok {
                    correction = Some(s);
                    break;
                }
                accepted += 1;
                emit!(s);
                if should_stop(generated, recent.len(), answer_from, in_think) {
                    done = true;
                    break;
                }
            }
            self.spec_stats.0 += accepted;
            if std::env::var_os("SPINDLE_SPEC_DEBUG").is_some() {
                let show = |ts: &[usize]| ts.iter().map(|&t| format!("{:?}", String::from_utf8_lossy(&self.token_bytes(t)))).collect::<Vec<_>>().join(" ");
                eprintln!("[spec] tok={} draft=[{}] accepted={accepted} correction={:?}", show(&[tok]), show(&draft), correction.map(|c| show(&[c])));
            }
            // `tok` and the accepted drafts are now valid KV; later positions get overwritten.
            self.cur_pos = start + 1 + accepted;
            if let Some(d) = draft_engine.as_mut() {
                d.cur_pos = d.cur_pos.min(reply_start + recent.len());
            }
            if done {
                break;
            }
            if accepted == 0 {
                backoff = (backoff * 2).clamp(1, 16);
                skip = backoff;
            } else {
                backoff = 0;
            }
            k_dyn = if accepted == draft.len() { (k_dyn + 2).min(7).max(self.draft_len) } else { self.draft_len };
            tok = match correction {
                Some(s) => s,
                None => self.sample_from_batch(draft.len(), penalty_window!(), generated < 2 || in_think, forbid_think),
            };
        }
        if !pending.is_empty() {
            let piece = String::from_utf8_lossy(&pending).into_owned();
            on_text(&piece);
            reply.push_str(&piece);
        }
        let gen_secs = t_gen.elapsed().as_secs_f64();
        if self.is_moe() {
            self.maybe_save_expert_stats();
        }
        if let Some((c0, r0)) = worker_t0 {
            if let Some((c1, r1)) = self.cluster_client.as_mut().and_then(|c| c.worker_timing()) {
                self.timing.worker_compute_us += c1.saturating_sub(c0);
                self.timing.worker_requests += r1.saturating_sub(r0);
            }
        }
        // Qwen3's chat template keeps only the final answer of earlier turns, not their
        // reasoning. Rewind the cache to the start of this reply and re-feed just the answer,
        // which also saves context (the reasoning is usually the longer part). Skipped if the
        // cache shifted during the reply, since `reply_start` no longer points at it.
        let mut rewound = false;
        if let Some(from) = answer_from {
            if self.kv_shifts == shifts_before {
                rewound = true;
                let answer: Vec<usize> = recent[from.min(recent.len())..]
                    .iter()
                    .copied()
                    .skip_while(|&t| self.idx.vocab[t].chars().all(|c| c == '\u{010A}'))
                    .collect();
                self.cur_pos = reply_start;
                self.feed(&answer);
                if let Some(draft) = draft_engine.as_mut() {
                    draft.cur_pos = reply_start;
                    draft.feed(&answer);
                }
            }
        }
        // Close the assistant turn in the cache (e.g. `<|im_end|>\n`) so the next user turn
        // follows the model's framing, whether we stopped on EOS or hit max_new_tokens.
        // The last emitted token (when we stopped on the length limit) was never fed; it
        // belongs in the cache before the turn is closed. A rewind already re-fed it.
        let mut closing = self.format.assistant_close.clone();
        if let (Some(t), false) = (unfed, rewound) {
            closing.insert(0, t);
        }
        self.feed(&closing);
        if let Some(draft) = draft_engine.as_mut() {
            draft.feed(&closing);
        }
        self.draft_engine = draft_engine;
        let total_secs = t0.elapsed().as_secs_f64();
        let (secs, toks) = if generated > 0 {
            (gen_secs, generated)
        } else {
            (total_secs, turn_ids.len())
        };
        (reply, secs, toks)
    }
